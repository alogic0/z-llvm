    };

    var eax_defined = function.ret_ty == .void or function.ret_ty.eql(.float) or function.ret_ty.eql(.double) or
        sysv_abi.aggregateReturnHasNoGpr(function.ret_ty);
    var saw_terminator = false;
    var rsp_mod16: u4 = 8;
    for (function.instructions.items) |instruction| switch (instruction) {
        .label => |label| {
            if (!std.mem.endsWith(u8, label, "generic_cfg_select_end") and
                !std.mem.endsWith(u8, label, "generic_cfg_pointer_select_end") and
                !std.mem.endsWith(u8, label, "conditional_slice_sum_skip"))
            {
                eax_defined = function.ret_ty == .void or sysv_abi.aggregateReturnHasNoGpr(function.ret_ty);
            }
        },
        .mov_imm_eax, .mov_imm_rax, .mov_arg_rax, .movq_xmm_rax, .mov_arg_eax, .binary_arg_eax, .add_arg64_rax, .add_arg_high32_eax, .add_stack_disp8_eax, .add_stack_disp8_rax, .add_stack_disp32_eax, .add_stack_disp32_rax, .add_eax_imm32, .shl_eax_imm5, .or_eax_imm32, .imul_eax_imm32, .and_eax_imm32, .shr_rax_imm6, .or_rdx_rax, .add_rax_imm8, .add_ecx_eax, .add_rdi_rcx4_ptr_eax, .add_r8d_eax, .load_rax_rdi_u8_eax, .smin_i32_edi_esi_eax, .shift_mix_i32_edi_esi_eax, .replace_low_i8_dil_sil_al, .read_flag_i8_dil_al, .load_stack_disp8_rax, .load_stack_disp32_rax, .load_stack_disp8_u8_eax, .load_stack_disp32_u8_eax, .load_stack_disp8_u16_eax, .load_stack_disp32_u16_eax, .load_rax_ptr_disp8_rax, .load_rax_ptr_eax, .load_arg_ptr_eax, .load_arg_ptr_disp8_rax, .load_arg_ptr_disp8_u8_eax, .add_arg_ptr_disp4_eax, .volatile_roundtrip_rdi_esi_eax, .load_global_i32_eax, .load_global_ptr_rax, .lea_global_rax, .load_tls_i32_eax, .add_tls_i32_eax, .atomic_xadd_global_eax, .mulsd_xmm1_xmm0, .mulss_xmm1_xmm0, .addsd_xmm1_xmm0, .addss_xmm1_xmm0, .subss_xmm1_xmm0, .divsd_xmm1_xmm0, .movapd_xmm1_xmm0, .movapd_xmm, .unpcklps_xmm, .shufps_high_f32_to_low, .cvtsi2ss_edi_xmm0, .cvtsi2sd_edi_xmm0, .cvtsi2ss_rdi_xmm0, .cvtsi2sd_rdi_xmm0, .cvttss2si_xmm0_eax, .cvttsd2si_xmm0_eax, .cvtsd2ss_xmm0_xmm0, .cvtss2sd_xmm0_xmm0, .mov_imm64_xmm0, .mov_imm32_xmm0, .load_f128_const_xmm0, .oltss_xmm0_xmm1_al => eax_defined = true,
        .mov_imm64_xmm => |load| {
            if (load.reg == .xmm0) eax_defined = true;
        },
        .mov_imm32_xmm => |load| {
            if (load.reg == .xmm0) eax_defined = true;
        },
        .mov_imm_rdi, .mov_imm_rdx, .mov_imm_rsi, .mov_imm_rcx, .mov_imm_r8, .mov_imm_r9, .mov_rax_rdi, .lea_global_rdi, .lea_global_rsi, .lea_global_rdx, .load_stack_disp8_arg32, .load_stack_disp8_arg64, .load_stack_disp32_arg32, .load_stack_disp32_arg64 => {},
        .reload_rsp_eax => {
            if (rsp_mod16 != 0) return error.StackSlotWithoutFrame;
            eax_defined = true;
        },
        .direct_call => |call| {
            if (rsp_mod16 != 0) return error.MisalignedStackBeforeCall;
            eax_defined = call.ret_ty != .void;
        },
        .indirect_call_rax => |ret_ty| {
            if (rsp_mod16 != 0) return error.MisalignedStackBeforeCall;
            eax_defined = ret_ty != .void;
        },
        .sub_rsp_8, .add_rsp_8 => rsp_mod16 = @intCast((@as(u8, rsp_mod16) + 8) % 16),
        .push_imm32, .push_stack_disp8, .push_stack_disp32, .push_arg, .push_rax, .push_xmm64 => rsp_mod16 = @intCast((@as(u8, rsp_mod16) + 8) % 16),
        .sub_rsp_24, .add_rsp_24 => rsp_mod16 = @intCast((@as(u8, rsp_mod16) + 24) % 16),
        .sub_rsp_40, .add_rsp_40 => rsp_mod16 = @intCast((@as(u8, rsp_mod16) + 40) % 16),
        .sub_rsp_56, .add_rsp_56 => rsp_mod16 = @intCast((@as(u8, rsp_mod16) + 56) % 16),
        .add_rsp_imm8 => |bytes| rsp_mod16 = @intCast((@as(u8, rsp_mod16) + bytes) % 16),
        .add_rsp_imm32 => |bytes| rsp_mod16 = @intCast((@as(u8, rsp_mod16) + bytes) % 16),
        .spill_arg_rsp => if (rsp_mod16 != 0) return error.StackSlotWithoutFrame,
        .reload_arg_rsp => if (rsp_mod16 != 0) return error.StackSlotWithoutFrame,
        .spill_xmm32_rsp, .spill_xmm64_rsp => if (rsp_mod16 != 0) return error.StackSlotWithoutFrame,
        .reload_xmm32_rsp, .reload_xmm64_rsp => {
            if (rsp_mod16 != 0) return error.StackSlotWithoutFrame;
            eax_defined = true;
        },
        .spill_rdi_rsi_rsp24, .reload_rdi_rsp24, .reload_rsi_rsp24 => {
            if (rsp_mod16 != 0) return error.StackSlotWithoutFrame;
        },
        .and_rsp_neg16 => rsp_mod16 = 0,
        .noreturn_direct_call => {
            if (rsp_mod16 != 0) return error.MisalignedStackBeforeCall;
            if (function.ret_ty != .void) return error.ReturnTypeMismatch;
            saw_terminator = true;
            eax_defined = true;
        },
        .base64_decode4_from_table_rax => {
            if (!function.ret_ty.eql(.{ .int = 64 })) return error.ReturnTypeMismatch;
            if (rsp_mod16 != 8) return error.UnbalancedStackFrame;
            saw_terminator = true;
            eax_defined = true;
        },
        .mov_arg_arg, .mov_arg64_arg, .shl_rdx_imm6, .shl_rcx_imm6, .or_rcx_rax, .or_rcx_rdx, .xor_ecx_ecx, .xor_ebp_ebp, .load_rdi_rcx4_ptr_r8d, .inc_rcx, .movzx_dil_edi, .and_edi_imm8, .mov_edi_edi, .mov_rsp_rdi, .load_rax_ptr_rdx, .cmp_ecx_arg32, .cmp_rcx_arg64, .cmp_r8d_arg32, .cmp_ecx_imm32, .cmp_eax_imm32, .cmp_arg64_imm64, .cmp_arg16_imm16, .cmp_rdi_imm64, .cmp_rdx_rdi, .cmp_rax_rdx, .cmp_arg8_imm8, .test_eax_eax, .test_rax_rax, .test_rdx_rdx, .test_arg8, .test_arg32, .test_arg64, .base64_raw_args_to_decode4_regs, .store_eax_arg_ptr, .store_imm64_arg_ptr_disp8, .store_arg64_arg_ptr_disp8, .store_arg64_arg_ptr_disp32, .store_rax_arg_ptr_disp8, .store_rax_arg_ptr_disp32, .store_eax_arg_ptr_disp8, .store_eax_arg_ptr_disp32, .store_al_arg_ptr_disp8, .store_al_arg_ptr_disp32, .store_ax_arg_ptr_disp8, .store_ax_arg_ptr_disp32, .store_xmm0_arg_ptr_disp8, .store_xmm0_arg_ptr_disp32, .store_xmm0_f32_arg_ptr_disp8, .store_xmm0_f32_arg_ptr_disp32, .store_imm8_arg_ptr_disp8, .load_stack_disp8_xmm0, .load_stack_disp32_xmm0, .load_stack_disp8_xmm0_f32, .load_stack_disp32_xmm0_f32, .load_stack_disp8_xmm, .load_stack_disp32_xmm, .mov_imm64_xmm1, .mov_imm32_xmm1, .ucomisd, .ucomisd_xmm1_xmm0, .ucomiss_xmm1_xmm0, .ucomiss_xmm0_xmm1, .load_f128_arg_ptr_xmm0, .load_f128_const_xmm1, .store_f128_xmm0_arg_ptr, .store_eax_global_i32, .store_eax_tls_i32, .store_imm8_abs, .je, .jne, .jo, .jp, .js, .jae, .jle, .jmp => {},
        .ret => {
            if (!eax_defined) return error.ReturnRegisterUndefined;
            if (rsp_mod16 != 8) return error.UnbalancedStackFrame;
            saw_terminator = true;
            eax_defined = function.ret_ty == .void;
        },
        .ud2 => {
            if (rsp_mod16 != 8) return error.UnbalancedStackFrame;
            saw_terminator = true;
            eax_defined = function.ret_ty == .void;
        },
    };
    if (!saw_terminator) return error.MissingMachineReturn;
}

