        .add_r8d_eax,
        .inc_rcx,
        .movzx_dil_edi,
        .and_edi_imm8,
        .load_rax_rdi_u8_eax,
        .smin_i32_edi_esi_eax,
        .shift_mix_i32_edi_esi_eax,
        .replace_low_i8_dil_sil_al,
        .read_flag_i8_dil_al,
        .store_imm8_abs,
        .cmp_ecx_arg32,
        .cmp_rcx_arg64,
        .cmp_arg64_imm64,
        .cmp_arg16_imm16,
        .cmp_rdi_imm64,
        .cmp_rdx_rdi,
        .cmp_rax_rdx,
        .test_eax_eax,
        .test_rax_rax,
        .test_rdx_rdx,
        .mulsd_xmm1_xmm0,
        .mulss_xmm1_xmm0,
        .addsd_xmm1_xmm0,
        .addss_xmm1_xmm0,
        .subss_xmm1_xmm0,
        .divsd_xmm1_xmm0,
        .movapd_xmm1_xmm0,
        .movapd_xmm,
        .unpcklps_xmm,
        .shufps_high_f32_to_low,
        .cvtsi2ss_edi_xmm0,
        .cvtsi2sd_edi_xmm0,
        .cvtsi2ss_rdi_xmm0,
        .cvtsi2sd_rdi_xmm0,
        .cvttss2si_xmm0_eax,
        .cvttsd2si_xmm0_eax,
        .cvtsd2ss_xmm0_xmm0,
        .cvtss2sd_xmm0_xmm0,
        .mov_edi_edi,
        .mov_imm64_xmm0,
        .mov_imm64_xmm1,
        .mov_imm32_xmm0,
        .mov_imm32_xmm1,
        .mov_imm64_xmm,
        .mov_imm32_xmm,
        .ucomisd,
        .ucomisd_xmm1_xmm0,
        .ucomiss_xmm1_xmm0,
        .ucomiss_xmm0_xmm1,
        .oltss_xmm0_xmm1_al,
        .sub_rsp_8,
        .add_rsp_8,
        .push_imm32,
        .push_stack_disp8,
        .push_stack_disp32,
        .push_arg,
        .push_rax,
        .push_xmm64,
        .sub_rsp_24,
        .add_rsp_24,
        .sub_rsp_40,
        .add_rsp_40,
        .sub_rsp_56,
        .add_rsp_56,
        .add_rsp_imm8,
        .add_rsp_imm32,
        .spill_arg_rsp,
        .reload_arg_rsp,
        .spill_xmm32_rsp,
        .reload_xmm32_rsp,
        .spill_xmm64_rsp,
        .reload_xmm64_rsp,
        .spill_rdi_rsi_rsp24,
        .reload_rdi_rsp24,
        .reload_rsi_rsp24,
        .reload_rsp_eax,
        .load_stack_disp8_rax,
        .load_stack_disp32_rax,
        .load_stack_disp8_u8_eax,
        .load_stack_disp32_u8_eax,
        .load_stack_disp8_u16_eax,
        .load_stack_disp32_u16_eax,
        .load_stack_disp8_xmm0,
        .load_stack_disp32_xmm0,
        .load_stack_disp8_xmm0_f32,
        .load_stack_disp32_xmm0_f32,
        .load_stack_disp8_xmm,
        .load_stack_disp32_xmm,
        .load_stack_disp8_arg32,
        .load_stack_disp8_arg64,
        .load_stack_disp32_arg32,
        .load_stack_disp32_arg64,
        .load_rax_ptr_disp8_rax,
        .load_rax_ptr_rdx,
        .load_rax_ptr_eax,
        .load_arg_ptr_eax,
        .load_arg_ptr_disp8_rax,
        .load_arg_ptr_disp8_u8_eax,
        .add_arg_ptr_disp4_eax,
        .store_eax_arg_ptr,
        .store_imm64_arg_ptr_disp8,
        .store_arg64_arg_ptr_disp8,
        .store_arg64_arg_ptr_disp32,
        .store_rax_arg_ptr_disp8,
        .store_rax_arg_ptr_disp32,
        .store_eax_arg_ptr_disp8,
        .store_eax_arg_ptr_disp32,
        .store_al_arg_ptr_disp8,
        .store_al_arg_ptr_disp32,
        .store_ax_arg_ptr_disp8,
        .store_ax_arg_ptr_disp32,
        .store_xmm0_arg_ptr_disp8,
        .store_xmm0_arg_ptr_disp32,
        .store_xmm0_f32_arg_ptr_disp8,
        .store_xmm0_f32_arg_ptr_disp32,
        .store_imm8_arg_ptr_disp8,
        .load_f128_arg_ptr_xmm0,
        .load_f128_const_xmm0,
        .load_f128_const_xmm1,
        .store_f128_xmm0_arg_ptr,
        .volatile_roundtrip_rdi_esi_eax,
        .load_global_i32_eax,
        .load_global_ptr_rax,
        .lea_global_rax,
        .lea_global_rdi,
        .lea_global_rsi,
        .lea_global_rdx,
        .store_eax_global_i32,
        .load_tls_i32_eax,
        .add_tls_i32_eax,
        .store_eax_tls_i32,
        .atomic_xadd_global_eax,
        .mov_rsp_rdi,
        .and_rsp_neg16,
        .direct_call,
        .indirect_call_rax,
        .noreturn_direct_call,
        .cmp_arg8_imm8,
        .cmp_ecx_imm32,
        .cmp_eax_imm32,
        .test_arg8,
        .test_arg32,
