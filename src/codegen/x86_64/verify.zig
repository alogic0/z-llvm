const machine_ir = @import("machine.zig");
const sysv_abi = @import("sysv_abi.zig");

const MachineFunction = machine_ir.MachineFunction;

pub fn verifyFunction(function: MachineFunction) !void {
    for (function.instructions.items) |instruction| switch (instruction) {
        .je, .jne, .jo, .jp, .js, .jae, .jle, .jmp => |target_name| if (!hasLabel(function, target_name)) return error.InvalidBranchTarget,
        .label,
        .mov_imm_eax,
        .mov_imm_rax,
        .mov_imm_rdi,
        .mov_imm_rdx,
        .mov_imm_rsi,
        .mov_imm_rcx,
        .mov_imm_r8,
        .mov_imm_r9,
        .mov_rax_rdi,
        .mov_arg_rax,
        .movq_xmm_rax,
        .mov_arg_eax,
        .mov_arg_arg,
        .mov_arg64_arg,
        .binary_arg_eax,
        .add_arg64_rax,
        .add_arg_high32_eax,
        .add_stack_disp8_eax,
        .add_stack_disp8_rax,
        .add_stack_disp32_eax,
        .add_stack_disp32_rax,
