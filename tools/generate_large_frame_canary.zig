//! Deterministic simultaneously-live multi-megabyte frame fixture.
const std = @import("std");
pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const argv = try init.minimal.args.toSlice(a);
    if (argv.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_large_frame_canary.zig.\ntarget triple = \"x86_64-unknown-linux-gnu\"\ndeclare void @large_frame_fill(ptr, i64, i64)\ndeclare i64 @large_frame_check(ptr, i64, i64)\ndeclare i64 @large_frame_probe_sink(ptr)\n\n");
    for ([_]u32{ 2, 4, 7 }) |megabytes| {
        const objects = megabytes;
        try w.print("define i64 @large_frame_{d}m(i64 %seed, i64 %salt, ptr %out) {{\nentry:\n %live = xor i64 %seed, %salt\n", .{megabytes});
        for (0..objects) |index|
            try w.print(" %object{d} = alloca [262144 x i32], align 16\n", .{index});
        for (0..objects) |index|
            try w.print(" call void @large_frame_fill(ptr %object{d}, i64 {d}, i64 %seed)\n", .{ index, index });
        for (0..objects) |index| {
            try w.print(" %value{d} = call i64 @large_frame_check(ptr %object{d}, i64 {d}, i64 %seed)\n", .{ index, index, index });
            if (index == 0) try w.writeAll(" %total0 = xor i64 %value0, %live\n") else try w.print(" %total{d} = xor i64 %value{d}, %total{d}\n", .{ index, index, index - 1 });
        }
        try w.print(" store i64 %total{d}, ptr %out, align 8\n %result = xor i64 %total{d}, %salt\n ret i64 %result\n}}\n\n", .{ objects - 1, objects - 1 });
    }
    try w.writeAll(
        \\define i64 @large_frame_probe() {
        \\entry:
        \\ %object = alloca [1835008 x i32], align 16
        \\ %result = call i64 @large_frame_probe_sink(ptr %object)
        \\ ret i64 %result
        \\}
        \\
    );
    const file = try std.Io.Dir.cwd().createFile(init.io, argv[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
