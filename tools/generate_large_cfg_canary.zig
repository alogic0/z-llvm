//! Deterministic source generator for the registered large-CFG native canary.
const std = @import("std");

fn chain(w: *std.Io.Writer, bits: u16, blocks: usize) !void {
    // Make a block address observable so the production optimizer preserves
    // the graph under test instead of spending this canary merging its chain.
    try w.print("@large_cfg_anchor_{d} = global [1 x ptr] [ptr blockaddress(@large_cfg_chain_{d}, %b{d})]\n", .{ bits, bits, blocks - 2 });
    try w.print("define i64 @large_cfg_chain_{d}(i64 %key, i64 %seed, ptr %out) {{\nentry:\n %anchor = load ptr, ptr @large_cfg_anchor_{d}\n %anchor_out = getelementptr i8, ptr %out, i64 8\n store ptr %anchor, ptr %anchor_out, align 1\n %noise = call i64 @large_cfg_noise(i64 %seed)\n", .{ bits, bits });
    if (bits == 32) try w.writeAll(" %v0 = trunc i64 %noise to i32\n %live = trunc i64 %seed to i32\n") else try w.writeAll(" %v0 = add i64 %noise, 0\n");
    try w.writeAll(" br label %b1\n");
    var last_value: usize = 0;
    for (1..blocks - 1) |i| {
        try w.print("b{d}:\n", .{i});
        // The largest topology carries changing SSA values across all of its
        // blocks. The 2,048-block case additionally updates at every edge.
        if (bits == 32 or i % 64 == 0 or i == blocks - 2) {
            try w.print(" %v{d} = add i{d} %v{d}, {d}\n", .{ i, bits, last_value, i });
            last_value = i;
        }
        if (i + 1 < blocks - 1) try w.print(" br label %b{d}\n", .{i + 1}) else try w.writeAll(" br label %exit\n");
    }
    try w.print("exit:\n store i{d} %v{d}, ptr %out, align 1\n %fold = xor i{d} %v{d}, %{s}\n", .{ bits, last_value, bits, last_value, if (bits == 32) "live" else "seed" });
    if (bits == 32) try w.writeAll(" %result = zext i32 %fold to i64\n ret i64 %result\n}\n\n") else try w.writeAll(" ret i64 %fold\n}\n\n");
}
fn labels(w: *std.Io.Writer, bits: u16) !void {
    var left: [406]u8 = @splat('l');
    var right = left;
    left[405] = 'a';
    right[405] = 'b';
    try w.print("define i64 @large_cfg_labels_{d}(i64 %key, i64 %seed, ptr %out) {{\nentry:\n %noise = call i64 @large_cfg_noise(i64 %seed)\n", .{bits});
    if (bits == 32) try w.writeAll(" %value = trunc i64 %noise to i32\n %live = trunc i64 %seed to i32\n") else try w.writeAll(" %value = add i64 %noise, 0\n");
    try w.print(" %bit = and i64 %key, 1\n %choose = icmp eq i64 %bit, 0\n br i1 %choose, label %{s}, label %{s}\n{s}:\n %a = add i{d} %value, 17\n br label %join\n{s}:\n %b = xor i{d} %value, 91\n br label %join\njoin:\n %v = phi i{d} [ %a, %{s} ], [ %b, %{s} ]\n store i{d} %v, ptr %out, align 1\n %fold = xor i{d} %v, %{s}\n", .{ &left, &right, &left, bits, &right, bits, bits, &left, &right, bits, bits, if (bits == 32) "live" else "seed" });
    if (bits == 32) try w.writeAll(" %result = zext i32 %fold to i64\n ret i64 %result\n}\n\n") else try w.writeAll(" ret i64 %fold\n}\n\n");
}
fn switches(w: *std.Io.Writer) !void {
    try w.writeAll("define i64 @large_cfg_switch(i64 %key, i64 %seed, ptr %out) {\nentry:\n %noise = call i64 @large_cfg_noise(i64 %seed)\n switch i64 %key, label %default [\n");
    for (0..1024) |i| try w.print("  i64 {d}, label %c{d}\n", .{ i, i });
    try w.writeAll("  i64 1024, label %c0\n  i64 1025, label %c0\n ]\n");
    for (0..1024) |i| {
        try w.print("c{d}:\n", .{i});
        if (i == 0) try w.writeAll(" %duplicate = phi i64 [ %noise, %entry ], [ %noise, %entry ], [ %noise, %entry ]\n");
        try w.print(" %v{d} = add i64 %{s}, {d}\n br label %join\n", .{ i, if (i == 0) "duplicate" else "noise", i * 37 + 7 });
    }
    try w.writeAll("default:\n %fallback = xor i64 %noise, 1073741823\n br label %join\njoin:\n %v = phi i64 [ %fallback, %default ]");
    for (0..1024) |i| try w.print(", [ %v{d}, %c{d} ]", .{ i, i });
    try w.writeAll("\n store i64 %v, ptr %out, align 1\n %fold = xor i64 %v, %seed\n ret i64 %fold\n}\n");
}
pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const argv = try init.minimal.args.toSlice(a);
    if (argv.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_large_cfg_canary.zig.\ntarget triple = \"x86_64-unknown-linux-gnu\"\ndeclare i64 @large_cfg_noise(i64)\n\n");
    try chain(w, 64, 20976);
    try chain(w, 32, 2048);
    try labels(w, 64);
    try labels(w, 32);
    try switches(w);
    const file = try std.Io.Dir.cwd().createFile(init.io, argv[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
