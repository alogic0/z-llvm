//! Deterministic power-of-two i16 tables; arbitrary lengths stay unsupported.
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_table_lengths_canary.zig.\n" ++
        "target triple = \"x86_64-unknown-linux-gnu\"\n" ++
        "target datalayout = \"e-m:e-i64:64-n8:16:32:64-S128\"\n\n");
    for ([_]usize{ 64, 256 }) |count| {
        try w.print("@length_table_{d} = private constant [{d} x i16] [", .{ count, count });
        for (0..count) |index| {
            if (index != 0) try w.writeAll(", ");
            try w.print("i16 {d}", .{(index * 257 + 0x9e37) & 65535});
        }
        try w.writeAll("], align 2\n");
        for ([_]bool{ false, true }) |copy| {
            try w.print("define i32 @length_table_{d}_{s}(i64 %index{s}) {{\nentry:\n" ++
                " %bounded = and i64 %index, {d}\n" ++
                " %address = getelementptr [2 x i8], ptr @length_table_{d}, i64 %bounded\n" ++
                " %value = load i16, ptr %address, align 2\n", .{
                count, if (copy) "copy" else "value", if (copy) ", ptr %out" else "", count - 1, count,
            });
            if (copy) try w.writeAll(" store i16 %value, ptr %out, align 2\n");
            try w.writeAll(" %wide = zext i16 %value to i32\n ret i32 %wide\n}\n");
            if (!copy) try w.writeByte('\n');
        }
    }
    const file = try std.Io.Dir.cwd().createFile(init.io, args[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
