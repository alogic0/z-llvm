//! Generate independent C/LLVM cross-boundary integer ABI checks.
const std = @import("std");
const u = @import("validation/common.zig");
const widths = [_]u16{ 65, 66, 80, 96, 127, 128 };
const prefixes = [_]usize{ 5, 7 };
const key: u64 = 0x9e3779b97f4a7c15;

fn values(w: *std.Io.Writer, count: usize) !void {
    for (0..count) |i| {
        try w.print(" %x{d} = add i64 %a, {d}\n %y{d} = xor i64 %x{d}, %b\n %v{d} = xor i64 %y{d}, %salt\n", .{ i, (@as(u64, @intCast(i)) + 1) *% key, i, i, i, i });
    }
}
fn signature(w: *std.Io.Writer, count: usize, named: bool) !void {
    for (0..count) |i| {
        if (i != 0) try w.writeAll(", ");
        if (named) try w.print("i64 %a{d}", .{i}) else try w.writeAll("i64");
    }
}
fn arguments(w: *std.Io.Writer, count: usize) !void {
    for (0..count) |i| try w.print("{s}i64 %v{d}", .{ if (i == 0) "" else ", ", i });
}
fn outputs(w: *std.Io.Writer) !void {
    try w.writeAll(
        \\ store i64 %low, ptr %out, align 8
        \\ %p1 = getelementptr i8, ptr %out, i64 8
        \\ store i64 %high, ptr %p1, align 8
        \\ %p2 = getelementptr i8, ptr %out, i64 16
        \\ store i64 %nested, ptr %p2, align 8
        \\ %p3 = getelementptr i8, ptr %out, i64 24
        \\ store i64 %probe, ptr %p3, align 8
        \\ %r0 = xor i64 %low, %high
        \\ %r1 = xor i64 %r0, %nested
        \\ %r2 = xor i64 %r1, %probe
        \\ %r3 = xor i64 %r2, %a
        \\ %r4 = xor i64 %r3, %b
        \\ %result = xor i64 %r4, %salt
        \\ ret i64 %result
        \\}
        \\
    );
}
fn cWords(w: *std.Io.Writer, count: usize, named: bool) !void {
    for (0..count) |i| {
        if (i != 0) try w.writeAll(",");
        if (named) try w.print("uint64_t a{d}", .{i}) else try w.writeAll("uint64_t");
    }
}
fn cWide(w: *std.Io.Writer, bits: u16, count: usize, named: bool) !void {
    try cWords(w, count, named);
    try w.writeAll(if (bits == 128) (if (named) ",u128 wide" else ",u128") else (if (named) ",uint64_t lo,uint64_t hi" else ",uint64_t,uint64_t"));
    try w.writeAll(if (named) ",uint64_t tail" else ",uint64_t");
}
fn cCallValues(w: *std.Io.Writer, bits: ?u16, count: usize) !void {
    for (0..count) |i| try w.print("{s}args[{d}]", .{ if (i == 0) "" else ",", i });
    if (bits) |width| try w.writeAll(if (width == 128) ",((u128)high<<64)|a,tail" else ",a,high,tail");
}

pub fn main(init: std.process.Init) !void {
    var c = try u.Context.init(init);
    const argv = try init.minimal.args.toSlice(c.a);
    const options = try u.Args.parse(c.a, argv[1..], &.{ "output-root", "registry-input" }, &.{});
    const output = try c.newOutput(try options.require("output-root"));
    var llvm: std.Io.Writer.Allocating = .init(c.a);
    var driver: std.Io.Writer.Allocating = .init(c.a);
    var entries: std.Io.Writer.Allocating = .init(c.a);
    var cases: std.Io.Writer.Allocating = .init(c.a);
    const w = &llvm.writer;
    const cw = &driver.writer;
    var names: std.ArrayList([]const u8) = .empty;
    try w.writeAll("; Generated by tools/generate_integer_physical_abi_canary.zig.\ntarget triple = \"x86_64-unknown-linux-gnu\"\ndeclare i64 @integer_abi_clobber(i64)\n");
    try cw.writeAll(@embedFile("templates/integer_physical_abi_header.c"));
    for ([_]usize{ 18, 32 }) |count| {
        const entry = try c.fmt("integer_abi_words{d}", .{count});
        const caller = try c.fmt("integer_abi_call_words{d}", .{count});
        const external = try c.fmt("integer_abi_external_words{d}", .{count});
        try names.appendSlice(c.a, &.{ entry, caller });
        try w.print("declare i64 @{s}(", .{external});
        try signature(w, count, false);
        try w.print(")\ndefine i64 @{s}(", .{entry});
        try signature(w, count, true);
        try w.writeAll(") {\nentry:\n %clobber = call i64 @integer_abi_clobber(i64 %a0)\n");
        for (0..count) |i| {
            try w.print(" %weight{d} = mul i64 %a{d}, {d}\n", .{ i, i, i * 2 + 1 });
            if (i == 0) try w.writeAll(" %sum0 = add i64 %weight0, 0\n") else try w.print(" %sum{d} = add i64 %sum{d}, %weight{d}\n", .{ i, i - 1, i });
        }
        try w.print(" %result = xor i64 %sum{d}, %clobber\n ret i64 %result\n}}\n", .{count - 1});
        try w.print("define i64 @{s}(i64 %a, i64 %b, i64 %salt, ptr %out) {{\nentry:\n", .{caller});
        try values(w, count);
        try w.writeAll(" %probe = call i64 @integer_abi_clobber(i64 %salt)\n %low = call i64 @");
        try w.print("{s}(", .{external});
        try arguments(w, count);
        try w.print(")\n %nested = call i64 @{s}(", .{entry});
        try arguments(w, count);
        try w.writeAll(")\n %high = add i64 0, 0\n");
        try outputs(w);
        try cw.print("extern uint64_t {s}(", .{entry});
        try cWords(cw, count, false);
        try cw.print(");\nextern uint64_t {s}(uint64_t,uint64_t,uint64_t,uint64_t*);\nuint64_t {s}(", .{ caller, external });
        try cWords(cw, count, true);
        try cw.writeAll(") { uint64_t hash=0;\n");
        for (0..count) |i| try cw.print(" hash+=a{d}*UINT64_C({d});\n", .{ i, i * 2 + 1 });
        try cw.writeAll(" return hash^integer_abi_clobber(a0); }\n");
        try entries.writer.print(" if(check_value({s}(", .{entry});
        try cCallValues(&entries.writer, null, count);
        try entries.writer.print("),word_expected(args,{d}),\"{s}\"))return 1;\n", .{ count, entry });
        try cases.writer.print(" {{{s},{d},0,0,0}},\n", .{ caller, count });
    }
    for (widths) |bits| for (prefixes) |count| {
        const entry = try c.fmt("integer_abi_entry{d}_{d}", .{ bits, count });
        const entry_cc = if (count == 7) "fastcc " else "";
        try names.append(c.a, entry);
        try w.print("define {s}i64 @{s}(", .{ entry_cc, entry });
        try signature(w, count, true);
        try w.print(", i{d} noundef %wide, i64 %tail) {{\nentry:\n %clobber = call i64 @integer_abi_clobber(i64 %a0)\n", .{bits});
        if (bits == 128) try w.writeAll(" %pair = add i128 %wide, 0\n") else try w.print(" %pair = zext i{d} %wide to i128\n", .{bits});
        try w.writeAll(" %low = trunc i128 %pair to i64\n %shift = lshr i128 %pair, 64\n %high = trunc i128 %shift to i64\n %lw = mul i64 %low, 3\n %hw = mul i64 %high, 5\n %sum0 = add i64 %lw, %hw\n");
        for (0..count) |i| try w.print(" %w{d} = mul i64 %a{d}, {d}\n %sum{d} = add i64 %sum{d}, %w{d}\n", .{ i, i, i * 2 + 1, i + 1, i, i });
        try w.print(" %tw = mul i64 %tail, 19\n %total = add i64 %sum{d}, %tw\n %result = xor i64 %total, %clobber\n ret i64 %result\n}}\n", .{count});
        try cw.print("extern uint64_t {s}(", .{entry});
        try cWide(cw, bits, count, false);
        try cw.writeAll(");\n");
        try entries.writer.print(" if(check_value({s}(", .{entry});
        try cCallValues(&entries.writer, bits, count);
        try entries.writer.print("),entry_expected(args,{d},((u128)high<<64)|a,tail,{d}),\"{s}\"))return 1;\n", .{ count, bits, entry });
        for ([_]bool{ false, true }) |constant| {
            const suffix = if (constant) "constant" else "value";
            const call_cc = if (constant) "fastcc " else "";
            const external = try c.fmt("integer_abi_external{d}_{d}_{s}", .{ bits, count, suffix });
            const caller = try c.fmt("integer_abi_call{d}_{d}_{s}", .{ bits, count, suffix });
            try names.append(c.a, caller);
            try w.print("declare {s}i{d} @{s}(", .{ call_cc, bits, external });
            try signature(w, count, false);
            try w.print(", i{d}, i64)\ndefine i64 @{s}(i64 %a, i64 %b, i64 %salt, ptr %out) {{\nentry:\n", .{ bits, caller });
            try values(w, count);
            try w.writeAll(" %lo128 = zext i64 %a to i128\n %hi128 = zext i64 %b to i128\n %shift128 = shl i128 %hi128, 64\n %wide128 = or i128 %lo128, %shift128\n");
            if (bits != 128) try w.print(" %wide = trunc i128 %wide128 to i{d}\n", .{bits});
            try w.print(" %probe = call i64 @integer_abi_clobber(i64 %salt)\n %raw = call {s}noundef i{d} @{s}(", .{ call_cc, bits, external });
            try arguments(w, count);
            const promise = if (constant) try c.fmt(" range(i{d} -1, 0)", .{bits}) else "";
            try w.print(", i{d} noundef{s} {s}, i64 %salt)\n %nested = call {s}i64 @{s}(", .{ bits, promise, if (constant) "-1" else if (bits == 128) "%wide128" else "%wide", entry_cc, entry });
            try arguments(w, count);
            try w.print(", i{d} %raw, i64 %salt)\n", .{bits});
            if (bits == 128) try w.writeAll(" %returned = add i128 %raw, 0\n") else try w.print(" %returned = zext i{d} %raw to i128\n", .{bits});
            try w.writeAll(" %low = trunc i128 %returned to i64\n %returned_shift = lshr i128 %returned, 64\n %high = trunc i128 %returned_shift to i64\n");
            try outputs(w);
            try cw.print("extern uint64_t {s}(uint64_t,uint64_t,uint64_t,uint64_t*);\nu128 {s}(", .{ caller, external });
            try cWide(cw, bits, count, true);
            try cw.writeAll(") {\n");
            if (bits != 128) try cw.writeAll(" u128 wide=((u128)hi<<64)|lo;\n");
            try cw.writeAll(" uint64_t hash=tail*19;\n");
            for (0..count) |i| try cw.print(" hash+=a{d}*UINT64_C({d});\n", .{ i, i * 2 + 1 });
            try cw.print(" (void)integer_abi_clobber(hash); return wide_expected(wide,hash,{d}) | ~mask_bits({d}); }}\n", .{ bits, bits });
            try cases.writer.print(" {{{s},0,{d},{d},{d}}},\n", .{ caller, bits, count, @intFromBool(constant) });
        }
    };
    try cw.writeAll("static const struct wrapper cases[]={\n");
    try cw.writeAll(cases.written());
    try cw.writeAll("};\n");
    try cw.writeAll(@embedFile("templates/integer_physical_abi_checks.c"));
    try cw.writeAll("int main(int argc,char **argv) {\n if(argc==2)inject_fault=(unsigned)strtoul(argv[1],0,10);\n if(argc>2||inject_fault>7)return 2;\n const uint64_t values[]={0,1,2,0x7fffffff,0x80000000,0x8000000000000000ULL,UINT64_MAX-1,UINT64_MAX};\n for(unsigned i=0;i<8;i++)for(unsigned j=0;j<8;j++)for(unsigned k=0;k<8;k++){\n uint64_t a=values[i],b=values[j],salt=values[k],high=b^salt,tail=a+salt,args[32];\n for(unsigned n=0;n<32;n++)args[n]=(a+(n+1)*abi_key)^b^salt;\n");
    try cw.writeAll(entries.written());
    try cw.writeAll(" for(unsigned n=0;n<sizeof(cases)/sizeof(cases[0]);n++)if(check_wrapper(cases+n,a,b,salt,args))return 1;\n }\n printf(\"integer-physical-abi observations=%u scalar=split=aligned=wide=nested=clobbers=guards=preserved\\n\",observations);\n return observations!=20480;\n}\n");
    try c.write(try c.join(&.{ output, "integer_physical_abi.ll" }), llvm.written());
    try c.write(try c.join(&.{ output, "integer_physical_abi_driver.c" }), driver.written());
    const population = try u.toValue(c.a, .{
        .population = "integer_physical_abi",
        .prefix = "integer-physical-abi",
        .fixture = "integer_physical_abi",
        .functions = names.items,
        .observations = 20480,
        .stdout = "integer-physical-abi observations=20480 scalar=split=aligned=wide=nested=clobbers=guards=preserved\n",
    });
    try c.writeJson(try c.join(&.{ output, "population.json" }), population);
    if (options.get("registry-input")) |path| {
        const original = try c.read(try c.join(&.{path}));
        const registry = try c.load(try c.join(&.{path}));
        for (try u.json.array(try u.get(registry, "canaries"))) |entry| {
            if (std.mem.eql(u8, try u.str(entry, "population"), "integer_physical_abi")) return error.PopulationAlreadyRegistered;
        }
        const end = std.mem.lastIndexOf(u8, original, "\n  ]") orelse return error.UnexpectedRegistryLayout;
        const rendered = try std.json.Stringify.valueAlloc(c.a, population, .{ .whitespace = .indent_2 });
        const indented = try std.mem.replaceOwned(u8, c.a, rendered, "\n", "\n    ");
        const updated = try c.fmt("{s},\n    {s}{s}", .{ original[0..end], indented, original[end..] });
        try c.write(try c.join(&.{ output, "native_canaries.json" }), updated);
    }
}
