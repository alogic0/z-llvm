//! Reproduce test/real_programs/register_pressure.ll on stdout.
//! The independently written C driver checks widths, calls and PHI permutations.
const std = @import("std");
pub fn main(init: std.process.Init) !void {
    var buffer: [65536]u8 = undefined;
    var output = std.Io.File.stdout().writerStreaming(init.io, &buffer);
    const w = &output.interface;
    try w.writeAll("; Generated by tools/generate_register_pressure_fixture.zig.\ntarget datalayout = \"e-m:e-p:64:64-i64:64-i128:128-n8:16:32:64-S128\"\ntarget triple = \"x86_64-unknown-linux-gnu\"\ndeclare i64 @pressure_clobber(i64)\n\n");
    for ([_]u16{ 32, 64 }) |bits| for ([_]usize{ 48, 96, 288 }) |count| {
        try w.print("define i64 @pressure_i{d}_{d}(ptr %data, i64 %salt) {{\nentry:\n", .{ bits, count });
        for (0..count) |i| {
            try w.print("  %address_{d} = getelementptr i8, ptr %data, i64 {d}\n", .{ i, i * 8 });
            try w.print("  %value_{d} = load i{d}, ptr %address_{d}, align 1\n", .{ i, bits, i });
            try w.print("  %alias_{d} = add i{d} %value_{d}, 0\n", .{ i, bits, i });
        }
        try w.writeAll("  %called = call i64 @pressure_clobber(i64 %salt)\n  %low = and i64 %salt, 1\n  %flag = icmp eq i64 %low, 0\n  br i1 %flag, label %left, label %right\nleft:\n  br label %join\nright:\n  br label %join\njoin:\n");
        for (0..count) |i| try w.print("  %phi_{d} = phi i{d} [ %alias_{d}, %left ], [ %value_{d}, %right ]\n", .{ i, bits, i, (i + 1) % count });
        for (0..count) |i| {
            try w.print("  %weight_{d} = mul i{d} %phi_{d}, {d}\n", .{ i, bits, i, i * 2 + 1 });
            if (i == 0) try w.print("  %sum_{d} = add i{d} %weight_{d}, 0\n", .{ i, bits, i }) else try w.print("  %sum_{d} = add i{d} %sum_{d}, %weight_{d}\n", .{ i, bits, i - 1, i });
        }
        if (bits == 32) try w.print("  %wide = zext i32 %sum_{d} to i64\n", .{count - 1}) else try w.print("  %wide = add i64 %sum_{d}, 0\n", .{count - 1});
        try w.writeAll("  %result = xor i64 %wide, %called\n  ret i64 %result\n}\n\n");
    };
    try w.flush();
}
