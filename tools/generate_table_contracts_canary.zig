//! Regression inputs for table layout, access eligibility and local symbols.
const std = @import("std");
const Case = enum { generic, layout, private_a, private_b, layout_probe };

fn table(w: *std.Io.Writer, name: []const u8, linkage: []const u8, seed: usize) !void {
    try w.print("@{s} = {s} constant [64 x i16] [", .{ name, linkage });
    for (0..64) |index| {
        if (index != 0) try w.writeAll(", ");
        try w.print("i16 {d}", .{(seed + index * 257) & 65535});
    }
    try w.writeAll("], align 2\n");
}

fn reader(w: *std.Io.Writer, name: []const u8, global: []const u8, before: []const u8, source: []const u8, indices: []const u8) !void {
    try w.print("define i32 @{s}(i64 %index) {{\nentry:\n{s} %p = getelementptr {s}, ptr @{s}, {s}\n %v = load i16, ptr %p, align 2\n %wide = zext i16 %v to i32\n ret i32 %wide\n}}\n", .{ name, before, source, global, indices });
}

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 3) return error.ExpectedCaseAndOutputPath;
    const selected = std.meta.stringToEnum(Case, args[1]) orelse return error.UnknownCase;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_table_contracts_canary.zig.\ntarget triple = \"x86_64-unknown-linux-gnu\"\n");
    const layout = selected == .layout or selected == .layout_probe;
    try w.print("target datalayout = \"{s}\"\n\n", .{if (layout) "e-p:64:64-i8:32-i16:16-i64:64" else "e-m:e-i64:64-n8:16:32:64-S128"});
    switch (selected) {
        .generic, .layout => {
            try table(w, "contract_table", "private", 0x9e37);
            if (selected == .layout) {
                try reader(w, "contract_layout", "contract_table", " %bounded = and i64 %index, 15\n", "[2 x i8]", "i64 %bounded");
            } else {
                try reader(w, "contract_unbounded", "contract_table", "", "[2 x i8]", "i64 %index");
                try reader(w, "contract_typed", "contract_table", "", "i16", "i64 %index");
                try reader(w, "contract_literal", "contract_table", "", "[2 x i8]", "i64 17");
                try reader(w, "contract_masked", "contract_table", " %bounded = and i64 %index, 63\n", "[2 x i8]", "i64 %bounded");
                try reader(w, "contract_stride4", "contract_table", " %bounded = and i64 %index, 15\n", "[4 x i8]", "i64 %bounded");
                try reader(w, "contract_array_element", "contract_table", "", "[64 x i16]", "i64 0, i64 %index");
            }
        },
        .private_a, .private_b => {
            const second = selected == .private_b;
            try table(w, "same_private_table", "private", if (second) 0x2222 else 0x1111);
            try table(w, "same_internal_table", "internal", if (second) 0x4444 else 0x3333);
            try table(w, "same_unused_table", "private", if (second) 0x6666 else 0x5555);
            try reader(w, if (second) "private_read_b" else "private_read_a", "same_private_table", " %bounded = and i64 %index, 63\n", "[2 x i8]", "i64 %bounded");
            try reader(w, if (second) "internal_read_b" else "internal_read_a", "same_internal_table", " %bounded = and i64 %index, 63\n", "[2 x i8]", "i64 %bounded");
        },
        .layout_probe => try w.writeAll("define i64 @layout_stride() {\nentry:\n %p = getelementptr [2 x i8], ptr null, i64 1\n %n = ptrtoint ptr %p to i64\n ret i64 %n\n}\n"),
    }
    const file = try std.Io.Dir.cwd().createFile(init.io, args[2], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
