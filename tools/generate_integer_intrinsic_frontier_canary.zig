//! Deterministic native cases for the remaining scalar integer intrinsic forms.
const std = @import("std");
const Case = struct { name: []const u8, op: enum { ssub, sadd, scmp, ctlz, abs, ignored_abs, fixed_mul, ushl_one }, bits: u16, variant: u2 = 0 };
pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const argv = try init.minimal.args.toSlice(a);
    if (argv.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_integer_intrinsic_frontier_canary.zig.\ntarget triple = \"x86_64-unknown-linux-gnu\"\ndeclare i64 @frontier_clobber(i64)\n");
    var cases: std.ArrayList(Case) = .empty;
    for ([_]u16{ 8, 16, 32, 64, 96 }) |bits| {
        for ([_]@FieldType(Case, "op"){ .ssub, .sadd }) |op| {
            try w.print("declare i{0d} @llvm.{1s}.sat.i{0d}(i{0d}, i{0d})\n", .{ bits, @tagName(op) });
            for (0..3) |variant| try cases.append(a, .{
                .name = try std.fmt.allocPrint(a, "frontier_{s}{d}{s}", .{ @tagName(op), bits, ([_][]const u8{ "", "_left", "_right" })[variant] }),
                .op = op,
                .bits = bits,
                .variant = @intCast(variant),
            });
        }
    }
    try w.writeAll("declare i32 @llvm.scmp.i32.i32(i32, i32)\ndeclare i128 @llvm.ctlz.i128(i128, i1 immarg)\n" ++
        "declare i32 @llvm.abs.i32(i32, i1 immarg)\ndeclare i64 @llvm.abs.i64(i64, i1 immarg)\n" ++
        "declare i16 @llvm.umul.fix.sat.i16(i16, i16, i32 immarg)\ndeclare i64 @llvm.ushl.sat.i64(i64, i64)\n\n");
    try cases.appendSlice(a, &.{
        .{ .name = "frontier_scmp32", .op = .scmp, .bits = 32 },
        .{ .name = "frontier_scmp32_left", .op = .scmp, .bits = 32, .variant = 1 },
        .{ .name = "frontier_ctlz128", .op = .ctlz, .bits = 128 },
        .{ .name = "frontier_ctlz128_poison", .op = .ctlz, .bits = 128, .variant = 1 },
        .{ .name = "frontier_abs32", .op = .abs, .bits = 32 },
        .{ .name = "frontier_abs64", .op = .abs, .bits = 64 },
        .{ .name = "frontier_abs32_ignored", .op = .ignored_abs, .bits = 32 },
        .{ .name = "frontier_abs64_ignored", .op = .ignored_abs, .bits = 64 },
        .{ .name = "frontier_mul_sat16", .op = .fixed_mul, .bits = 16 },
        .{ .name = "frontier_mul_sat16_left", .op = .fixed_mul, .bits = 16, .variant = 1 },
        .{ .name = "frontier_mul_sat16_right", .op = .fixed_mul, .bits = 16, .variant = 2 },
        .{ .name = "frontier_ushl64_one", .op = .ushl_one, .bits = 64 },
        .{ .name = "frontier_ushl64_one_constant", .op = .ushl_one, .bits = 64, .variant = 1 },
    });
    for (cases.items) |case| {
        try w.print("define i64 @{s}(i64 %a, i64 %b, i64 %salt, ptr %out) {{\nentry:\n", .{case.name});
        if (case.op == .ctlz) {
            try w.writeAll(" %lo = zext i64 %a to i128\n %hi = zext i64 %b to i128\n %shift = shl i128 %hi, 64\n %pair = or i128 %lo, %shift\n");
        } else if (case.bits == 96) {
            try w.writeAll(" %left_hi64 = and i64 %b, 4294967295\n %left_lo = zext i64 %a to i128\n %left_hi = zext i64 %left_hi64 to i128\n" ++
                " %left_shift = shl i128 %left_hi, 64\n %left_pair = or i128 %left_lo, %left_shift\n %left = trunc i128 %left_pair to i96\n" ++
                " %right_hi64 = and i64 %a, 4294967295\n %right_lo = zext i64 %b to i128\n %right_hi = zext i64 %right_hi64 to i128\n" ++
                " %right_shift = shl i128 %right_hi, 64\n %right_pair = or i128 %right_lo, %right_shift\n %right = trunc i128 %right_pair to i96\n");
        } else if (case.bits < 64) {
            try w.print(" %left = trunc i64 %a to i{0d}\n %right = trunc i64 %b to i{0d}\n", .{case.bits});
        } else try w.writeAll(" %left = add i64 %a, 0\n %right = add i64 %b, 0\n");
        try w.writeAll(" %first = call i64 @frontier_clobber(i64 %salt)\n");
        switch (case.op) {
            .ssub, .sadd => {
                const left = if (case.variant == 1) try std.fmt.allocPrint(a, "{d}", .{@as(u128, 1) << @as(u7, @intCast(case.bits - 1))}) else "%left";
                const right = if (case.variant == 2) try std.fmt.allocPrint(a, "{d}", .{(@as(u128, 1) << @as(u7, @intCast(case.bits))) - 1}) else "%right";
                try w.print(" %raw = call i{0d} @llvm.{1s}.sat.i{0d}(i{0d} {2s}, i{0d} {3s})\n", .{ case.bits, @tagName(case.op), left, right });
            },
            .scmp => try w.print(" %raw = call i32 @llvm.scmp.i32.i32(i32 {s}, i32 %right)\n", .{if (case.variant == 1) "0" else "%left"}),
            .ctlz => try w.print(" %raw = call range(i128 0, 129) i128 @llvm.ctlz.i128(i128 noundef %pair, i1 {s})\n", .{if (case.variant == 1) "true" else "false"}),
            .abs, .ignored_abs => try w.print(" %raw = call i{0d} @llvm.abs.i{0d}(i{0d} %left, i1 true)\n", .{case.bits}),
            .fixed_mul => try w.print(" %raw = call i16 @llvm.umul.fix.sat.i16(i16 {s}, i16 {s}, i32 0)\n", .{ if (case.variant == 1) "65535" else "%left", if (case.variant == 2) "65535" else "%right" }),
            .ushl_one => try w.print(" %raw = call i64 @llvm.ushl.sat.i64(i64 {s}, i64 1)\n", .{if (case.variant == 1) "18446744073709551615" else "%left"}),
        }
        try w.writeAll(" %second = call i64 @frontier_clobber(i64 %a)\n");
        if (case.op == .ctlz) {
            try w.writeAll(" %wide = trunc i128 %raw to i64\n %high = lshr i128 %raw, 64\n %upper = trunc i128 %high to i64\n");
        } else if (case.bits == 96) {
            try w.writeAll(" %result_pair = zext i96 %raw to i128\n %wide = trunc i128 %result_pair to i64\n %high = lshr i128 %result_pair, 64\n %upper = trunc i128 %high to i64\n");
        } else {
            if (case.op == .ignored_abs) try w.writeAll(" %wide = add i64 %b, 0\n") else if (case.bits < 64) try w.print(" %wide = zext i{d} %raw to i64\n", .{case.bits}) else try w.writeAll(" %wide = add i64 %raw, 0\n");
            try w.writeAll(" %upper = add i64 0, 0\n");
        }
        try w.writeAll(" store i64 %wide, ptr %out, align 8\n %out1 = getelementptr i8, ptr %out, i64 8\n store i64 %upper, ptr %out1, align 8\n" ++
            " %out2 = getelementptr i8, ptr %out, i64 16\n store i64 %first, ptr %out2, align 8\n" ++
            " %out3 = getelementptr i8, ptr %out, i64 24\n store i64 %second, ptr %out3, align 8\n" ++
            " %sum = add i64 %a, %b\n %live = xor i64 %sum, %salt\n %ret0 = add i64 %live, %first\n %ret = xor i64 %ret0, %second\n ret i64 %ret\n}\n\n");
    }
    const file = try std.Io.Dir.cwd().createFile(init.io, argv[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
