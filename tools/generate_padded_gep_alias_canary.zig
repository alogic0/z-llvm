//! Distinct byte stores reached through padded allocation strides.
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll(
        \\; Generated by tools/generate_padded_gep_alias_canary.zig.
        \\target datalayout = "e-m:e-p:64:64-i24:32-i64:64-f80:128-n8:16:32:64-S128"
        \\target triple = "x86_64-unknown-linux-gnu"
        \\
    );
    const cases = [_]struct { name: []const u8, ty: []const u8, store: i64 }{
        .{ .name = "i24", .ty = "i24", .store = 3 },
        .{ .name = "f80", .ty = "x86_fp80", .store = 10 },
        .{ .name = "i40", .ty = "i40", .store = 5 },
        .{ .name = "vector", .ty = "<3 x i32>", .store = 12 },
    };
    for (cases) |case| for ([_]i64{ 1, -1 }) |direction| {
        try w.print(
            \\define i8 @padded_{s}{s}(ptr %base) {{
            \\entry:
            \\  %p = getelementptr {s}, ptr %base, i64 {d}
            \\  %q = getelementptr i8, ptr %base, i64 {d}
            \\  store i8 11, ptr %q, align 1
            \\  store i8 22, ptr %p, align 1
            \\  %v = load i8, ptr %q, align 1
            \\  ret i8 %v
            \\}}
            \\
            \\
        , .{ case.name, if (direction < 0) "_negative" else "", case.ty, direction, case.store * direction });
    };
    const file = try std.Io.Dir.cwd().createFile(init.io, args[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, std.mem.trimEnd(u8, output.written(), "\n"));
    try file.writeStreamingAll(init.io, "\n");
}
