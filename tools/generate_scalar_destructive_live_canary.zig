//! Reproduce live scalar sources across destructive operations and loop edges.
const std = @import("std");
pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len != 2) return error.ExpectedFreshOutput;
    const file = try std.Io.Dir.cwd().createFile(init.io, args[1], .{ .exclusive = true });
    defer file.close(init.io);
    var buffer: [8192]u8 = undefined;
    var writer = file.writerStreaming(init.io, &buffer);
    const w = &writer.interface;
    try w.writeAll("; Generated by tools/generate_scalar_destructive_live_canary.zig.\n" ++
        "target triple = \"x86_64-unknown-linux-gnu\"\n");
    for ([_]u16{ 16, 32, 64 }) |bits| {
        for ([_]bool{ false, true }) |loop| {
            try w.print("define i64 @destructive_{s}{d}(ptr %input, i64 %amount, i64 %count, ptr %out) {{\nentry:\n", .{ if (loop) "loop" else "shift", bits });
            if (bits < 64) try w.print(" %shift = trunc i64 %amount to i{d}\n", .{bits}) else try w.writeAll(" %shift = add i64 %amount, 0\n");
            try w.print(" %first = load i{d}, ptr %input, align 1\n", .{bits});
            if (loop) {
                try w.print(" %negative = sub i{0d} 0, %shift\n %left_count = and i{0d} %negative, {1d}\n", .{ bits, bits - 1 });
                try w.print(" br label %loop\nloop:\n %current = phi i{d} [%first, %entry], [%next, %loop]\n", .{bits});
                try w.print(" %index = phi i64 [0, %entry], [%next_index, %loop]\n %right = lshr i{d} %current, %shift\n", .{bits});
                try w.print(" %next_index = add i64 %index, 1\n %address = getelementptr i{0d}, ptr %input, i64 %next_index\n" ++
                    " %next = load i{0d}, ptr %address, align 1\n %left = shl i{0d} %next, %left_count\n" ++
                    " %merged = or i{0d} %left, %right\n", .{bits});
                if (bits < 64) try w.print(" %wide = zext i{d} %merged to i64\n", .{bits}) else try w.writeAll(" %wide = add i64 %merged, 0\n");
                try w.writeAll(" %destination = getelementptr i64, ptr %out, i64 %index\n store i64 %wide, ptr %destination, align 8\n" ++
                    " %more = icmp ult i64 %next_index, %count\n br i1 %more, label %loop, label %done\ndone:\n");
                if (bits < 64) try w.print(" %original = zext i{d} %next to i64\n", .{bits}) else try w.writeAll(" %original = add i64 %next, 0\n");
            } else {
                for ([_][]const u8{ "shl", "lshr", "ashr" }, 0..) |op, index| {
                    try w.print(" %value{0d} = {1s} i{2d} %first, %shift\n", .{ index, op, bits });
                    if (bits < 64) try w.print(" %wide{d} = zext i{d} %value{d} to i64\n", .{ index, bits, index }) else try w.print(" %wide{d} = add i64 %value{d}, 0\n", .{ index, index });
                    try w.print(" %destination{0d} = getelementptr i64, ptr %out, i64 {0d}\n store i64 %wide{0d}, ptr %destination{0d}, align 8\n", .{index});
                }
                if (bits < 64) try w.print(" %original = zext i{d} %first to i64\n", .{bits}) else try w.writeAll(" %original = add i64 %first, 0\n");
            }
            try w.writeAll(" ret i64 %original\n}\n");
        }
    }
    for ([_][]const u8{ "and", "or" }) |op| try w.print(
        "define i64 @destructive_bool_{0s}(ptr %input, i64 %amount, i64 %count, ptr %out) {{\nentry:\n" ++
            " %first = load i1, ptr %input, align 1\n %second = trunc i64 %amount to i1\n" ++
            " %value = {0s} i1 %first, %second\n %wide = zext i1 %value to i64\n store i64 %wide, ptr %out, align 8\n" ++
            " %original = zext i1 %first to i64\n ret i64 %original\n}}\n",
        .{op},
    );
    try w.flush();
}
