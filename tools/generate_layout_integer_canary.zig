//! Integer alignment follows the next declared width, then the largest width.
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll(
        \\; Generated by tools/generate_layout_integer_canary.zig.
        \\target datalayout = "e-m:e-p:64:64-i16:32-i32:64-i64:64-n8:16:32:64-S128"
        \\target triple = "x86_64-unknown-linux-gnu"
        \\
    );
    const cases = [_]struct { name: []const u8, ty: []const u8 }{
        .{ .name = "i80_array", .ty = "[1 x i80]" },
        .{ .name = "i80_struct", .ty = "{ i8, i80 }" },
        .{ .name = "i24_array", .ty = "[1 x i24]" },
        .{ .name = "i24_struct", .ty = "{ i8, i24 }" },
        .{ .name = "i9_array", .ty = "[1 x i9]" },
    };
    for (cases) |case| {
        try w.print(
            \\define i64 @layout_{s}(i64 %seed) {{
            \\entry:
            \\  %size_ptr = getelementptr {s}, ptr null, i64 1
            \\  %size = ptrtoint ptr %size_ptr to i64
            \\  %align_ptr = getelementptr {{ <8 x i1>, {s} }}, ptr null, i64 0, i32 1
            \\  %alignment = ptrtoint ptr %align_ptr to i64
            \\  %high = shl i64 %size, 16
            \\  %encoded = or i64 %high, %alignment
            \\  %result = xor i64 %seed, %encoded
            \\  ret i64 %result
            \\}}
            \\
            \\
        , .{ case.name, case.ty, case.ty });
    }
    const file = try std.Io.Dir.cwd().createFile(init.io, args[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, std.mem.trimEnd(u8, output.written(), "\n"));
    try file.writeStreamingAll(init.io, "\n");
}
