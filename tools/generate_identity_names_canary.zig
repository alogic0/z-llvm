//! Long raw and quoted scalar sources; action/external names stay unchanged.
const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_identity_names_canary.zig.\n" ++
        "target triple = \"x86_64-unknown-linux-gnu\"\n" ++
        "target datalayout = \"e-m:e-i64:64-n8:16:32:64-S128\"\n" ++
        "declare i64 @identity_sink(i64, i64)\n\n");
    // Above the former 512-byte identity bound, within LLVM's default
    // non-global name limit. Strict composed tests separately extend to 4 KiB.
    const prefix: [768]u8 = @splat('n');
    for ([_][]const u8{ "identity_sum", "identity_difference", "identity_mix", "identity_call" }, 0..) |function, index| {
        const left = if (index == 1) try std.fmt.allocPrint(a, "%\"{s}\\61\"", .{prefix}) else try std.fmt.allocPrint(a, "%{s}a", .{prefix});
        const right = if (index == 1) try std.fmt.allocPrint(a, "%\"{s}\\62\"", .{prefix}) else try std.fmt.allocPrint(a, "%{s}b", .{prefix});
        try w.print("define i64 @{s}(i64 {s}, i64 {s}) {{\nentry:\n", .{ function, left, right });
        switch (index) {
            0, 1 => try w.print(" %result = {s} i64 {s}, {s}\n", .{ if (index == 0) "add" else "sub", left, right }),
            2 => try w.print(" %bits = xor i64 {s}, {s}\n %sum = add i64 %bits, {s}\n %result = sub i64 %sum, {s}\n", .{ left, right, left, right }),
            3 => try w.print(" %result = call i64 @identity_sink(i64 {s}, i64 {s})\n", .{ left, right }),
            else => unreachable,
        }
        try w.writeAll(" ret i64 %result\n}\n");
        if (index != 3) try w.writeByte('\n');
    }
    const file = try std.Io.Dir.cwd().createFile(init.io, args[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
