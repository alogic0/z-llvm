//! Deterministic original-address/parallel-PHI native fixture generator.
const std = @import("std");
const Kind = enum { integer, floating, pointer };
fn function(w: *std.Io.Writer, kind: Kind, bits: u16) !void {
    const name = try std.fmt.allocPrint(std.heap.page_allocator, "indirect_phi_{s}_{d}", .{ @tagName(kind), bits });
    defer std.heap.page_allocator.free(name);
    var integer_buffer: [16]u8 = undefined;
    const integer = try std.fmt.bufPrint(&integer_buffer, "i{d}", .{bits});
    const ty = switch (kind) {
        .integer => integer,
        .floating => switch (bits) {
            16 => "half",
            32 => "float",
            64 => "double",
            else => unreachable,
        },
        .pointer => "ptr",
    };
    try w.print("@{s}_table = internal constant [2 x ptr] [ptr blockaddress(@{s}, %exit), ptr blockaddress(@{s}, %loop)]\n", .{ name, name, name });
    if (kind == .pointer) try w.print("define i64 @{s}(i64 %count, ptr %first, ptr %second, ptr %out, i64 %seed) {{\nentry:\n %a = getelementptr i8, ptr %first, i64 0\n %b = getelementptr i8, ptr %second, i64 0\n", .{name}) else {
        try w.print("define i64 @{s}(i64 %count, i64 %seed, i64 %alt, ptr %out) {{\nentry:\n", .{name});
        if (bits < 64) try w.print(" %abits = trunc i64 %seed to {s}\n %bbits = trunc i64 %alt to {s}\n", .{ integer, integer }) else if (bits == 64) try w.writeAll(" %abits = add i64 %seed, 0\n %bbits = add i64 %alt, 0\n") else try w.print(" %lo = zext i64 %seed to {s}\n %hi = zext i64 %alt to {s}\n %shifted = shl {s} %hi, 64\n %abits = or {s} %lo, %shifted\n %bbits = xor {s} %abits, -1\n", .{ integer, integer, integer, integer, integer });
        if (kind == .floating) try w.print(" %a = bitcast {s} %abits to {s}\n %b = bitcast {s} %bbits to {s}\n", .{ integer, ty, integer, ty }) else try w.print(" %a = add {s} %abits, 0\n %b = add {s} %bbits, 0\n", .{ ty, ty });
    }
    try w.print(" %more0 = icmp ne i64 %count, 0\n %index0 = zext i1 %more0 to i64\n %slot0 = getelementptr ptr, ptr @{s}_table, i64 %index0\n %raw0 = load ptr, ptr %slot0\n %target0 = call ptr @indirect_phi_target(ptr %raw0)\n indirectbr ptr %target0, [label %loop, label %exit]\nloop:\n %lx = phi {s} [ %a, %entry ], [ %ly, %loop ]\n %ly = phi {s} [ %b, %entry ], [ %lx, %loop ]\n %i = phi i64 [ 0, %entry ], [ %next, %loop ]\n %noise = call i64 @indirect_phi_noise(i64 %i)\n %next = add i64 %i, 1\n %more = icmp ult i64 %next, %count\n %index = zext i1 %more to i64\n %slot = getelementptr ptr, ptr @{s}_table, i64 %index\n %raw = load ptr, ptr %slot\n %target = call ptr @indirect_phi_target(ptr %raw)\n indirectbr ptr %target, [label %loop, label %exit]\nexit:\n %x = phi {s} [ %a, %entry ], [ %ly, %loop ]\n %y = phi {s} [ %b, %entry ], [ %lx, %loop ]\n %last = phi i64 [ %seed, %entry ], [ %noise, %loop ]\n %out_y = getelementptr i8, ptr %out, i64 16\n", .{ name, ty, ty, name, ty, ty });
    if (kind == .floating) {
        // Observe exact bits through the already supported integer memory
        // contract; half stores through arbitrary pointers are a separate edge.
        try w.print(" %xmemory = bitcast {s} %x to {s}\n %ymemory = bitcast {s} %y to {s}\n store {s} %xmemory, ptr %out, align 1\n store {s} %ymemory, ptr %out_y, align 1\n", .{ ty, integer, ty, integer, integer, integer });
    } else try w.print(" store {s} %x, ptr %out, align 1\n store {s} %y, ptr %out_y, align 1\n", .{ ty, ty });
    if (kind == .pointer) try w.writeAll(" %x64 = load i64, ptr %x, align 1\n %y64 = load i64, ptr %y, align 1\n") else {
        if (kind == .floating) try w.print(" %xbits = bitcast {s} %x to {s}\n %ybits = bitcast {s} %y to {s}\n", .{ ty, integer, ty, integer }) else try w.print(" %xbits = add {s} %x, 0\n %ybits = add {s} %y, 0\n", .{ integer, integer });
        if (bits < 64) try w.print(" %x64 = zext {s} %xbits to i64\n %y64 = zext {s} %ybits to i64\n", .{ integer, integer }) else if (bits == 64) try w.writeAll(" %x64 = add i64 %xbits, 0\n %y64 = add i64 %ybits, 0\n") else try w.print(" %xlo = trunc {s} %xbits to i64\n %ylo = trunc {s} %ybits to i64\n %xshift = lshr {s} %xbits, 64\n %yshift = lshr {s} %ybits, 64\n %xhi = trunc {s} %xshift to i64\n %yhi = trunc {s} %yshift to i64\n %x64 = xor i64 %xlo, %xhi\n %y64 = xor i64 %ylo, %yhi\n", .{ integer, integer, integer, integer, integer, integer });
    }
    try w.writeAll(" %both = xor i64 %x64, %y64\n %with_noise = xor i64 %both, %last\n %result = xor i64 %with_noise, %seed\n ret i64 %result\n}\n\n");
}
pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const argv = try init.minimal.args.toSlice(a);
    if (argv.len != 2) return error.ExpectedOutputPath;
    var output: std.Io.Writer.Allocating = .init(a);
    const w = &output.writer;
    try w.writeAll("; Generated by tools/generate_indirect_phi_canary.zig.\ntarget triple = \"x86_64-unknown-linux-gnu\"\ndeclare i64 @indirect_phi_noise(i64)\ndeclare ptr @indirect_phi_target(ptr)\n\n");
    for ([_]u16{ 1, 2, 8, 16, 24, 32, 40, 56, 64, 65, 96, 128 }) |bits| try function(w, .integer, bits);
    for ([_]u16{ 16, 32, 64 }) |bits| try function(w, .floating, bits);
    try function(w, .pointer, 64);
    try w.writeAll(
        \\@indirect_phi_poison_table = internal constant [2 x ptr] [ptr blockaddress(@indirect_phi_inactive_poison, %good), ptr blockaddress(@indirect_phi_inactive_poison, %bad)]
        \\define i64 @indirect_phi_inactive_poison(i64 %key, i64 %seed, i64 %alt, ptr %out) {
        \\entry:
        \\ %overflow = add nuw i64 %seed, 1
        \\ %index = and i64 %key, 1
        \\ %slot = getelementptr ptr, ptr @indirect_phi_poison_table, i64 %index
        \\ %raw = load ptr, ptr %slot
        \\ %target = call ptr @indirect_phi_target(ptr %raw)
        \\ indirectbr ptr %target, [label %good, label %bad]
        \\good:
        \\ %defined = phi i64 [ %seed, %entry ]
        \\ store i64 %defined, ptr %out, align 1
        \\ ret i64 %defined
        \\bad:
        \\ %incremented = phi i64 [ %overflow, %entry ]
        \\ store i64 %incremented, ptr %out, align 1
        \\ ret i64 %incremented
        \\}
        \\
    );
    const file = try std.Io.Dir.cwd().createFile(init.io, argv[1], .{ .exclusive = true });
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, output.written());
}
